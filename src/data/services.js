export function getServicePage(slug) {
  return servicePages.find((p) => p.slug === slug) || null
}

export function getServiceProjects(page) {
  if (!page) return []
  return page.projectIds
    .map((id) => projects.find((p) => p.id === id))
    .filter(Boolean)
}

export function serviceCanonical(slug) {
  const origin = getSiteOrigin()
  const path = `/services/${slug}/`
  return origin ? `${origin}${path}` : path
}

/** URL без query — для письма FormSubmit и разметки */
export function servicePageUrl(slug) {
  return serviceCanonical(slug).split('?')[0]
}

export function serviceNav() {
  return servicePages.map((p) => ({
    slug: p.slug,
    href: `services/${p.slug}/`,
    label:
      p.slug === 'auto'
        ? 'Автобизнес'
        : p.slug === 'beauty'
          ? 'Красота'
          : 'Цветы',
  }))
}

